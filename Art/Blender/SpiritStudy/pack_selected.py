"""Pack approved-model renders and emit one shared C++ atlas description."""
import hashlib
import json
import math
from pathlib import Path

from PIL import Image

OUT=Path(__file__).resolve().parent
ROOT=OUT.parents[2]
DEST=OUT/'SelectedA'
report=json.loads((DEST/'render_manifest.json').read_text(encoding='utf-8'))
cell,columns,rows=report['cellSize'],report['columns'],report['rows']
sheet=Image.new('RGBA',(cell*columns,cell*rows))
bounds=None
for row in range(rows):
    for col in range(columns):
        image=Image.open(DEST/'Frames'/f'd{row}_f{col:02d}.png').convert('RGBA')
        assert image.size==(cell,cell)
        box=image.getchannel('A').getbbox()
        if not box or min(box[:2])<2 or max(box[2:])>cell-2:
            raise ValueError(f'Empty or clipped selected pose: {row},{col}: {box}')
        bounds=box if bounds is None else (min(bounds[0],box[0]),min(bounds[1],box[1]),max(bounds[2],box[2]),max(bounds[3],box[3]))
        sheet.alpha_composite(image,(col*cell,row*cell))
for path,h in report['protectedBefore'].items():
    assert hashlib.sha256((ROOT/path).read_bytes()).hexdigest()==h==report['protectedAfter'][path]
target=ROOT/'SimpleGame/Assets/Spirits/Forgotten/lantern_a.png'
target.parent.mkdir(parents=True,exist_ok=True)
sheet.save(target)
height=(bounds[3]-bounds[1])/cell
# Use one constant origin for every clip, keeping all trailing fabric above the ground.
anchor=max(report['worldOriginAnchorY'],(bounds[3]+2)/cell)
assert anchor<1
idle,glide,cast=(report['clips'][kind] for kind in ['idle','glide','cast'])
header=f'''// Generated by Art/Blender/SpiritStudy/pack_selected.py; retain clip/layout agreement.
#pragma once

namespace ForgottenAppearance
{{
constexpr wchar_t Sprite[] = L"Assets/Spirits/Forgotten/lantern_a.png";
constexpr int Columns = {columns}, Rows = {rows};
constexpr int IdleFirst = {idle['first']}, IdleFrames = {idle['frames']};
constexpr int GlideFirst = {glide['first']}, GlideFrames = {glide['frames']};
constexpr int CastFirst = {cast['first']}, CastFrames = {cast['frames']};
constexpr float LoopSeconds = 1.333333333f;
constexpr float AnchorY = {anchor:.9f}f;
constexpr float CharacterHeight = {height:.9f}f;
}} // namespace ForgottenAppearance
'''
(ROOT/'SimpleGame/ForgottenAppearance.h').write_text(header,encoding='utf-8')
report.update({'status':'selected_A_atlas_packed','atlas':str(target.relative_to(ROOT)),
               'dimensions':list(sheet.size),'alphaBounds':list(bounds),'canvasAnchorY':anchor,
               'canvasCharacterHeight':height,'rgbaBytes':sheet.width*sheet.height*4,
               'atlasSha256':hashlib.sha256(target.read_bytes()).hexdigest(),
               'emptyCells':0,'clippedCells':0,'selectionAccepted':True,
               'runtimeAssetReady':True})
(DEST/'runtime_manifest.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print('SELECTED_A_PACKED',sheet.size,'anchor',anchor,'height',height,flush=True)
