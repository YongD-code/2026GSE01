"""Pack three spirit atlases and emit the shared four-species appearance table.

Requires completed create_spirits.py renders for pilgrim/hands/saint and selected A.
Produces PNGs and C++ metadata only; never changes IDs, old artwork or saves.
"""
import hashlib
import json
from pathlib import Path

from PIL import Image

OUT=Path(__file__).resolve().parent
ROOT=OUT.parents[2]
selected=json.loads((ROOT/'Art/Blender/SpiritStudy/SelectedA/runtime_manifest.json').read_text(encoding='utf-8'))
definitions=[('Forgotten/lantern_a.png',selected['canvasAnchorY'],selected['canvasCharacterHeight'],selected['loopSeconds'])]
for key in ['pilgrim','hands','saint']:
    folder=OUT/key
    report=json.loads((folder/'render_manifest.json').read_text(encoding='utf-8'))
    assert report['clips']==selected['clips'] and report['columns']==32 and report['rows']==8
    assert len(report['directionYaws'])==8
    cell=report['cellSize']
    atlas=Image.new('RGBA',(cell*32,cell*8))
    bounds=None
    for row in range(8):
        for col in range(32):
            picture=Image.open(folder/'Frames'/f'd{row}_f{col:02d}.png').convert('RGBA')
            assert picture.size==(cell,cell)
            box=picture.getchannel('A').getbbox()
            if not box or min(box[:2])<2 or max(box[2:])>cell-2:
                raise ValueError(f'Empty or clipped spirit pose: {key} {row},{col}: {box}')
            bounds=box if bounds is None else (min(bounds[0],box[0]),min(bounds[1],box[1]),max(bounds[2],box[2]),max(bounds[3],box[3]))
            atlas.alpha_composite(picture,(col*cell,row*cell))
    for path,h in report['protectedBefore'].items():
        assert hashlib.sha256((ROOT/path).read_bytes()).hexdigest()==h==report['protectedAfter'][path]
    target=ROOT/f'SimpleGame/Assets/Spirits/Models/{key}.png'
    target.parent.mkdir(parents=True,exist_ok=True)
    anchor=max(report['worldOriginAnchorY'],(bounds[3]+2)/cell)
    height=(bounds[3]-bounds[1])/cell
    assert anchor<1 and height>0
    atlas.save(target)
    report.update({'status':'integrated_model_atlas','runtimeIntegrated':True,
                   'atlas':str(target.relative_to(ROOT)),'dimensions':list(atlas.size),
                   'canvasAnchorY':anchor,'canvasCharacterHeight':height,'alphaBounds':list(bounds),
                   'rgbaBytes':atlas.width*atlas.height*4,'emptyCells':0,'clippedCells':0,
                   'atlasSha256':hashlib.sha256(target.read_bytes()).hexdigest()})
    (folder/'runtime_manifest.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    definitions.append((f'Models/{key}.png',anchor,height,report['loopSeconds']))
    print('SPIRIT_ATLAS',key,atlas.size,flush=True)
rows='\n'.join(f'        {{L"Assets/Spirits/{path}", {anchor:.9f}f, {height:.9f}f, {period:.9f}f}},'
               for path,anchor,height,period in definitions)
header='''// Generated by Art/Blender/SpiritCollection/pack_spirits.py.
#pragma once
#include "SpiritCatalog.h"
#include "ForgottenAppearance.h"
#include <array>

namespace SpiritAppearance
{
constexpr int Columns = ForgottenAppearance::Columns, Rows = ForgottenAppearance::Rows;
constexpr int IdleFirst = ForgottenAppearance::IdleFirst, IdleFrames = ForgottenAppearance::IdleFrames;
constexpr int GlideFirst = ForgottenAppearance::GlideFirst, GlideFrames = ForgottenAppearance::GlideFrames;
constexpr int CastFirst = ForgottenAppearance::CastFirst, CastFrames = ForgottenAppearance::CastFrames;

struct Definition
{
    const wchar_t* sprite;
    float anchorY, characterHeight, loopSeconds;
};

inline const Definition& Get(int species)
{
    static const std::array<Definition, SpiritCatalog::Count> definitions = {{
%s
    }};
    return definitions[species >= 0 && species < SpiritCatalog::Count ? species : 0];
}
} // namespace SpiritAppearance
''' % rows
(ROOT/'SimpleGame/SpiritAppearance.h').write_text(header,encoding='utf-8')
print('SPIRIT_APPEARANCE_TABLE_READY',flush=True)
